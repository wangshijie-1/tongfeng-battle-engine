const unsigned short* Font::findCn(unsigned int codepoint)
{
    for (unsigned i = 0; i < sizeof(g_cnFont) / sizeof(g_cnFont[0]); ++i)
    {
        if (g_cnFont[i].code == codepoint)
            return g_cnFont[i].data;
    }
    return nullptr;
}

void Font::drawAscii(Screen* scr, int x, int y, char c, int color, int scale)
{
    const unsigned char* glyph = nullptr;
    for (unsigned i = 0; i < sizeof(g_asciiTable) / sizeof(g_asciiTable[0]); ++i)
    {
        if (g_asciiTable[i].c == c)
        {
            glyph = g_asciiTable[i].data;
            break;
        }
    }
    if (!glyph) return;  // 未收录字符：留空

    for (int row = 0; row < 8; ++row)
    {
        unsigned char bits = glyph[row];
        for (int col = 0; col < 8; ++col)
        {
            if (bits & (0x80 >> col))
            {
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        scr->draw_point(x + col * scale + sx, y + row * scale + sy, color);
            }
        }
    }
}

void Font::drawCn(Screen* scr, int x, int y, unsigned int codepoint, int color, int scale)
{
    const unsigned short* glyph = findCn(codepoint);
    if (!glyph) return;  // 未收录汉字：留空

    for (int row = 0; row < 16; ++row)
    {
        unsigned short bits = glyph[row];
        for (int col = 0; col < 16; ++col)
        {
            if (bits & (0x8000 >> col))
            {
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        scr->draw_point(x + col * scale + sx, y + row * scale + sy, color);
            }
        }
    }
}

int Font::textWidth(const char* text, int scale)
{
    if (!text) return 0;
    int w = 0;
    const unsigned char* p = (const unsigned char*)text;
    while (*p)
    {
        if (*p < 0x80)
        {
            w += 8 * scale;
            ++p;
        }
        else if ((*p & 0xF0) == 0xE0)
        {
            w += 16 * scale;
            p += 3;
        }
        else if ((*p & 0xE0) == 0xC0)
        {
            w += 8 * scale;
            p += 2;
        }
        else
        {
            ++p;
        }
    }
    return w;
}

void Font::drawText(Screen* scr, int x, int y, const char* text, int color, int scale)
{
    if (!scr || !text) return;

    int xpos = x;
    const unsigned char* p = (const unsigned char*)text;
    while (*p)
    {
        if (*p < 0x80)
        {
            // ASCII 单字节
            drawAscii(scr, xpos, y, (char)*p, color, scale);
            xpos += 8 * scale;
            ++p;
        }
        else if ((*p & 0xF0) == 0xE0)
        {
            // 中文三字节 UTF-8
            unsigned int cp = ((p[0] & 0x0F) << 12) |
                              ((p[1] & 0x3F) << 6)  |
                              (p[2] & 0x3F);
            drawCn(scr, xpos, y, cp, color, scale);
            xpos += 16 * scale;
            p += 3;
        }
        else if ((*p & 0xE0) == 0xC0)
        {
            // 两字节（本库未收录）：跳过宽度占位
            xpos += 8 * scale;
            p += 2;
        }
        else
        {
            ++p;
        }
    }
}
